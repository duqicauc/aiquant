#!/bin/bash
# 模型更新流水线脚本
# 自动执行完整的模型更新流程

set -e  # 遇到错误立即退出

echo "================================================================================"
echo "🚀 开始模型更新流程"
echo "================================================================================"

# 切换到项目根目录
cd "$(dirname "$0")/.."

# Step 1: 准备正样本
echo ""
echo "================================================================================"
echo "Step 1: 准备正样本"
echo "================================================================================"
python scripts/prepare_positive_samples.py
if [ $? -ne 0 ]; then
    echo "❌ 正样本准备失败！"
    exit 1
fi

# Step 2: 准备负样本
echo ""
echo "================================================================================"
echo "Step 2: 准备负样本"
echo "================================================================================"
python scripts/prepare_negative_samples_v2.py
if [ $? -ne 0 ]; then
    echo "❌ 负样本准备失败！"
    exit 1
fi

# Step 3: 数据质量检查
echo ""
echo "================================================================================"
echo "Step 3: 数据质量检查"
echo "================================================================================"
python scripts/check_sample_quality.py
if [ $? -ne 0 ]; then
    echo "❌ 数据质量检查失败！"
    exit 1
fi

# Step 4: 训练新模型
echo ""
echo "================================================================================"
echo "Step 4: 训练新模型"
echo "================================================================================"
python scripts/train_xgboost_timeseries.py
if [ $? -ne 0 ]; then
    echo "❌ 模型训练失败！"
    exit 1
fi

# Step 5: Walk-forward验证
echo ""
echo "================================================================================"
echo "Step 5: Walk-forward验证"
echo "================================================================================"
python scripts/walk_forward_validation.py
if [ $? -ne 0 ]; then
    echo "❌ 模型验证失败！"
    exit 1
fi

# 完成
echo ""
echo "================================================================================"
echo "✅ 模型更新流程完成！"
echo "================================================================================"
echo ""
echo "📁 模型文件位置: data/models/stock_selection/"
echo "📊 验证结果位置: data/backtest/reports/"
echo ""
echo "💡 下一步:"
echo "   1. 查看验证结果，确认模型表现"
echo "   2. 如果满意，可以开始使用新模型进行预测"
echo "   3. 运行: python scripts/weekly_prediction.py"
echo ""
